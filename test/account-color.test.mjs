import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {mkdtemp, mkdir, rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {readContactCatalog} from '../contact-catalog.mjs';
import {ContactBook} from '../contacts.mjs';
import {Directory} from '../directory.mjs';

test('slack portal ids keep their workspace, and other accounts stay one color key', async t => {
 const dir = await mkdtemp(path.join(os.tmpdir(), 'chord-accounts-'));
 t.after(() => rm(dir, {recursive: true, force: true}));
 await mkdir(path.join(dir, 'runtime/slack'), {recursive: true});
 const db = new DatabaseSync(path.join(dir, 'runtime/slack/bridge.db'));
 db.exec(`
  CREATE TABLE user_login (id TEXT, user_mxid TEXT, remote_name TEXT);
  CREATE TABLE ghost (id TEXT, name TEXT, is_bot INT, identifiers TEXT);
  CREATE TABLE portal (id TEXT, receiver TEXT, mxid TEXT, name TEXT, room_type TEXT, other_user_id TEXT);
  CREATE TABLE message (room_id TEXT, room_receiver TEXT, sender_id TEXT, sender_mxid TEXT, timestamp INT);
 `);
 db.prepare('INSERT INTO user_login VALUES (?,?,?)').run('TEMMBGZU3-U1', '@max:chord.local', 'Garcia-Bosch Lab');
 db.prepare('INSERT INTO user_login VALUES (?,?,?)').run('TSAU3JLKZ-U1', '@max:chord.local', '15-112 Staff Fall 2026');
 const portal = db.prepare('INSERT INTO portal VALUES (?,?,?,?,?,?)');
 portal.run('TEMMBGZU3-C1', '', '!lab', '#general', '', null);
 portal.run('TSAU3JLKZ-D1', '', '!course', 'Stella Lim', 'dm', 'TSAU3JLKZ-USTELLA');
 portal.run('TEMMBGZU3', '', '!space', 'Garcia-Bosch Lab', 'space', null);
 db.close();
 const catalog = readContactCatalog(dir);
 const lab = catalog.rooms.get('!lab');
 const course = catalog.rooms.get('!course');
 assert.equal(lab.workspaceID, 'TEMMBGZU3');
 assert.equal(lab.workspaceName, 'Garcia-Bosch Lab');
 assert.equal(course.workspaceID, 'TSAU3JLKZ');
 assert.equal(course.workspaceName, '15-112 Staff Fall 2026');
 assert.equal(catalog.rooms.has('!space'), false);
 const book = new ContactBook(dir);
 book.save = async () => {};
 const directory = new Directory(book, {blue: async () => [], config: () => ({})});
 directory.catalog = catalog;
 const channel = directory.enrichConversation({id: 'matrix:!lab', remoteId: '!lab', kind: 'chat', source: 'slack', title: '#general', participants: []});
 const dm = directory.enrichConversation({id: 'matrix:!course', remoteId: '!course', kind: 'chat', source: 'slack', title: 'Stella Lim', participants: []});
 const discord = directory.enrichConversation({id: 'matrix:!discord', remoteId: '!discord', kind: 'chat', source: 'discord', title: '#rides', participants: []});
 const home = directory.enrichConversation({id: 'mail:home:1', remoteId: '1', kind: 'email', source: 'mail:home', title: 'Notes', participants: []});
 const cmu = directory.enrichConversation({id: 'mail:cmu:1', remoteId: '1', kind: 'email', source: 'mail:cmu', title: 'Lab', participants: []});
 assert.equal(channel.accountKey, 'slack:TEMMBGZU3');
 assert.equal(channel.accountName, 'Garcia-Bosch Lab');
 assert.equal(dm.accountKey, 'slack:TSAU3JLKZ');
 assert.equal(dm.accountName, '15-112 Staff Fall 2026');
 assert.notEqual(channel.accountKey, dm.accountKey);
 assert.equal(discord.accountKey, 'discord');
 assert.equal(discord.accountName, null);
 assert.equal(home.accountKey, 'mail:home');
 assert.equal(cmu.accountKey, 'mail:cmu');
});
